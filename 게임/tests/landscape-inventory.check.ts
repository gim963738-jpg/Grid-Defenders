import {Defense} from '../src/defense';
import {GRID,BAG_GRID,ITEMS,RULES,LANDSCAPE_BATTLE,rotated} from '../src/defenseConfig';
import {inventoryPlacement,commitInventoryPlacement,combinationPartners,inventoryCombinationLinks,type InventoryPick} from '../src/landscape-inventory';

export function checkLandscapeInventory(){
 const passed:string[]=[];
 const check=(ok:boolean,name:string)=>{if(!ok)throw Error(name);passed.push(name);};
 const game=new Defense(()=>.5);game.gold=10000;game.anvils=10;
 game.summon('melee',0);const hero=game.heroes()[0];
 game.shop=[ITEMS[0],ITEMS[0],ITEMS[2],ITEMS[1]];game.shopDiscounts=[false,false,false,false];
 game.buy(0,{x:0,y:0});game.buy(1,{x:2,y:0});
 const [a,b]=game.gear,pick:InventoryPick={kind:'gear',id:a.id};
 check(GRID.columns*GRID.rows===20,'horizontal hero equipment retains 20 cells');
 check(combinationPartners(game,pick).includes(b.id),'owned ingredient identifies the blue-line partner');
 check(inventoryCombinationLinks(game).some(link=>link.a===a.id&&link.b===b.id&&link.ready),'adjacent ingredients form the yellow planned link');
 const snapshot=()=>JSON.stringify({gear:game.gear,gold:game.gold,shop:game.shop});
 const before=snapshot(),edge=inventoryPlacement(game,pick,null,BAG_GRID.columns-1,2)!;
 check(snapshot()===before,'placement preview does not mutate inventory or charge gold');
 check(edge.allowed&&edge.cells.every(([dx,dy])=>edge.x+dx<BAG_GRID.columns&&edge.x+dx>=0&&edge.y+dy>=0),'bag-edge footprint is fully inside its columns');
 check(commitInventoryPlacement(game,pick,edge),'corrected bag-edge preview can be committed');
 check(a.x===edge.x&&a.y===edge.y,'committed bag position matches its preview');
 const overlap=inventoryPlacement(game,pick,null,b.x,b.y)!;
 const unchanged=snapshot();check(!overlap.allowed&&!commitInventoryPlacement(game,pick,overlap)&&snapshot()===unchanged,'bag overlap rejects atomically without moving the source');
 const offer:InventoryPick={kind:'offer',index:2};
 const price=game.shopPrice(2),gold=game.gold;
 const heroEdge=inventoryPlacement(game,offer,hero.id,GRID.columns-1,GRID.rows-1)!;
 check(heroEdge.allowed&&heroEdge.cells.every(([dx,dy])=>heroEdge.x+dx<GRID.columns&&heroEdge.y+dy<GRID.rows),'direct purchase previews inside the rotated horizontal hero board');
 check(commitInventoryPlacement(game,offer,heroEdge)&&game.gold===gold-price,'direct purchase charges exactly the existing discounted price');
 const equipped=game.gear.at(-1)!;
 check(equipped.owner===hero.id&&equipped.x===heroEdge.x&&equipped.y===heroEdge.y,'direct purchase uses the exact preview owner and cells');
 const heroOverlap=inventoryPlacement(game,pick,hero.id,equipped.x,equipped.y)!;
 check(heroOverlap.allowed&&heroOverlap.warning,'hero overlap keeps the original warning rather than bag-style rejection');
 check(commitInventoryPlacement(game,pick,heroOverlap),'intentional hero overlap retains the existing placement rule');
 check([...game.gearStates(hero.id).values()].some(state=>!state.active),'overlapped hero equipment does not silently grant all bonuses');
 const money=game.gold;check(!commitInventoryPlacement(game,offer,heroEdge)&&game.gold===money,'stale sold-out offer cannot be purchased twice');
 const held:InventoryPick={kind:'gear',id:equipped.id};
 game.rotateGear(equipped.id);const turn=inventoryPlacement(game,held,hero.id,GRID.columns-1,GRID.rows-1)!;
 check(turn.allowed&&turn.turns===equipped.turns&&turn.cells.every(([dx,dy])=>turn.x+dx<GRID.columns&&turn.y+dy<GRID.rows),'rotation at an edge preserves the model footprint and stays inside');
 check(!inventoryPlacement(game,pick,999,0,0)!.allowed,'missing hero rejects a drop');
 check(!inventoryPlacement(game,pick,null,NaN,0)!.allowed,'non-finite pointer coordinates never move items');
 game.gold=0;check(!inventoryPlacement(game,{kind:'offer',index:3},hero.id,0,0)!.allowed,'insufficient currency is shown as an invalid purchase preview');
 game.gold=10000;
 game.gear=game.gear.filter(item=>item.owner!==hero.id);
 for(let i=0;i<20;i++)game.gear.push({id:100+i,def:ITEMS[4],owner:hero.id,x:i%GRID.columns,y:Math.floor(i/GRID.columns),turns:0,order:100+i,costBasis:100});
 const full=inventoryPlacement(game,{kind:'offer',index:3},hero.id,0,0)!;
 const fullBefore=snapshot();check(!full.allowed&&!commitInventoryPlacement(game,{kind:'offer',index:3},full)&&snapshot()===fullBefore,'full horizontal hero board rejects purchase without losing items or gold');
 const dev=new Defense(()=>.5);dev.summon('melee',0);check(dev.devEquipHero(dev.heroes()[0].id),'developer test loadout supports either board orientation');
 check(dev.gear.every(item=>!dev.outside(item,item.owner,item.x,item.y,item.turns)),'developer loadout contains no protruding footprint');
 check(dev.gear.reduce((sum,item)=>sum+rotated(item.def.cells,item.turns).length,0)===19,'transposed test loadout retains all 19 occupied cells');
 const combo=new Defense(()=>.5);combo.gold=1000;combo.anvils=1;combo.shop=[ITEMS[0],ITEMS[0]];combo.shopDiscounts=[false,false];
 combo.buy(0,{x:0,y:0});combo.buy(1,{x:2,y:0});
 check(combo.combineMany(combo.combinationPlan(null))&&combo.anvils===0&&combo.gear.length===1,'the same yellow-line pair is consumed once by combine');
 check(inventoryCombinationLinks(combo).length===0&&combo.gear[0].def.id==='I06','completed combination removes obsolete links and uses the existing recipe');
 const capacity=new Defense(()=>.5);capacity.gold=10000;capacity.shopDiscounts=[false];
 for(let y=0;y<BAG_GRID.rows;y++)for(let x=0;x<BAG_GRID.columns;x++){
  capacity.shop=[ITEMS[4]];capacity.buy(0,{x,y});
 }
 check(capacity.gear.length===BAG_GRID.columns*BAG_GRID.rows&&capacity.bagRows()===BAG_GRID.rows,'all initial bag columns are usable before extending below');
 capacity.shop=[ITEMS[0]];
 const capacitySnapshot=()=>JSON.stringify({gear:capacity.gear,gold:capacity.gold,shop:capacity.shop,anvils:capacity.anvils});
 const capacityBefore=capacitySnapshot(),purchased=capacity.buy(0);
 if(LANDSCAPE_BATTLE){
  check(!purchased&&capacitySnapshot()===capacityBefore&&capacity.bagRows()===3,'full fixed bag rejects purchase without charging or extending');
  check(!inventoryPlacement(capacity,{kind:'offer',index:0},null,0,0)!.allowed,'full bag purchase preview is invalid');
  capacity.summon('melee',0);const owner=capacity.heroes()[0].id;
  check(capacity.buy(0,undefined,owner),'full common bag still allows a direct hero equipment purchase');
  const equipped=capacity.gear.at(-1)!,equippedBefore=capacitySnapshot();
  check(!capacity.unequip(equipped.id)&&capacitySnapshot()===equippedBefore,'unequip into full bag preserves equipped item and currencies');
  check(!capacity.placeInBag(equipped.id,0,3,0)&&capacitySnapshot()===equippedBefore,'out-of-bounds transfer into full bag preserves original owner');
  check(!capacity.devEquipHero(owner)&&capacitySnapshot()===equippedBefore,'developer loadout is atomic when old equipment cannot fit in the fixed bag');
  check(capacity.outside(equipped,null,0,3,0)&&!capacity.canPlace(equipped,null,0,3,0),'fixed bag bounds reject hidden fourth-row placements');
  const rotation=new Defense(()=>.5);rotation.gold=10000;rotation.shop=[ITEMS[0]];rotation.shopDiscounts=[false];rotation.buy(0,{x:0,y:2});
  const sword=rotation.gear[0];
  for(let y=0;y<3;y++)for(let x=0;x<BAG_GRID.columns;x++)if(rotation.canPlace({id:-1,def:ITEMS[4]},null,x,y,0)){rotation.shop=[ITEMS[4]];rotation.buy(0,{x,y});}
  const rotationBefore=JSON.stringify(rotation.gear);
  check(!rotation.rotateGear(sword.id)&&JSON.stringify(rotation.gear)===rotationBefore,'rotation without enough fixed-bag space retains the item and original orientation');
 }else check(purchased&&capacity.gear.at(-1)!.y===BAG_GRID.rows&&capacity.bagRows()===BAG_GRID.rows+1,'legacy bag still extends exactly one row for the next purchase');
 const shop=new Defense(()=>.5);
 check(shop.shop.length===RULES.shopSlots&&RULES.shopSlots===(LANDSCAPE_BATTLE?6:5),'shop starts with the requested slot count for its layout');
 shop.reroll();check(shop.shop.length===RULES.shopSlots,'shop refresh retains every product slot');
 shop.reset();check(shop.shop.length===RULES.shopSlots,'new battle restores every product slot');
 return passed;
}
